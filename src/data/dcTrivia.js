const TODAY_KEY = 'dc-trivia-today'
const STREAK_KEY = 'dc-trivia-streak'
const HISTORY_KEY = 'dc-trivia-history'

function getTodayStr() {
  return new Date().toISOString().slice(0, 10)
}

function getDailyQuestion() {
  const today = getTodayStr()
  const seed = today.split('-').reduce((a, b) => a * 31 + parseInt(b, 10), 0)
  return DC_TRIVIA_QUESTIONS[seed % DC_TRIVIA_QUESTIONS.length]
}

export function getDCDailyTrivia() {
  const today = getTodayStr()
  try {
    const saved = JSON.parse(localStorage.getItem(TODAY_KEY) ?? '{}')
    const q = getDailyQuestion()
    return { question: q, answeredToday: saved.date === today ? saved : null }
  } catch {
    return { question: getDailyQuestion(), answeredToday: null }
  }
}

export function saveDCTriviaAnswer(correct) {
  const today = getTodayStr()
  const result = { date: today, correct }
  try { localStorage.setItem(TODAY_KEY, JSON.stringify(result)) } catch {}

  // Update streak
  try {
    const history = JSON.parse(localStorage.getItem(HISTORY_KEY) ?? '[]')
    history.push({ date: today, correct })
    localStorage.setItem(HISTORY_KEY, JSON.stringify(history.slice(-90)))
    const streak = JSON.parse(localStorage.getItem(STREAK_KEY) ?? '{ "current": 0, "best": 0 }')
    if (correct) {
      streak.current = (streak.current ?? 0) + 1
      streak.best = Math.max(streak.best ?? 0, streak.current)
    } else {
      streak.current = 0
    }
    localStorage.setItem(STREAK_KEY, JSON.stringify(streak))
  } catch {}
  return result
}

export function getDCTriviaStreak() {
  try { return JSON.parse(localStorage.getItem(STREAK_KEY) ?? '{ "current": 0, "best": 0 }') } catch { return { current: 0, best: 0 } }
}
